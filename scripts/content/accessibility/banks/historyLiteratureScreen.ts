import type { AccessibleCategory, AccessibleQuestion } from '../types';

type TextPair = readonly [en: string, et: string];
type VariantPair = readonly [en: readonly string[], et: readonly string[]];
type QuestionSeed = readonly [
  factKey: string,
  subjectKey: string,
  clue: TextPair,
  response: TextPair,
  explanation: TextPair,
  sourceReference: string,
  acceptedVariants: VariantPair,
];

const ASSIGNED_BATCHES = new Set([
  '01-history',
  '04-literature-language',
  '07-film-television',
]);

const assignedTargets = LEGACY_EASY_TARGETS.filter(({ batchId }) =>
  ASSIGNED_BATCHES.has(batchId));
const titleById = new Map<string, (typeof CATEGORY_TITLES)[number]>(
  CATEGORY_TITLES.map((title) => [title.categorySetId, title]),
);
const targetById = new Map<string, (typeof assignedTargets)[number]>(
  assignedTargets.map((target) => [target.categorySetId, target]),
);

function source(reference: string): AccessibleQuestion['source'] {
  const wiktionary = reference.startsWith('wikt:');
  const page = wiktionary ? reference.slice('wikt:'.length) : reference;
  const decodedPage = decodeURIComponent(page);
  const site = wiktionary ? 'Wiktionary' : 'Wikipedia';
  const host = wiktionary ? 'en.wiktionary.org' : 'en.wikipedia.org';
  return {
    sourceId: `${site.toLowerCase()}:${decodedPage.toLocaleLowerCase('en')
      .replace(/[^\p{L}\p{N}]+/gu, '-').replace(/^-|-$/gu, '')}`,
    title: `${decodedPage.replaceAll('_', ' ')} — ${site}`,
    url: `https://${host}/wiki/${page}`,
    license: 'CC-BY-SA-4.0',
    retrievedAt: '2026-08-28',
  };
}

function category(categorySetId: string, seeds: readonly QuestionSeed[]): AccessibleCategory {
  const target = targetById.get(categorySetId);
  const title = titleById.get(categorySetId);
  if (target === undefined || title === undefined) {
    throw new Error(`Missing approved target or title: ${categorySetId}`);
  }
  return {
    categorySetId,
    batchId: target.batchId,
    name: title.name,
    questions: seeds.map((seed, index) => {
      const [factKey, subjectKey, clue, response, explanation, reference, variants] = seed;
      return {
        key: factKey,
        tier: (index + 1) as AccessibleQuestion['tier'],
        subjectKey,
        clue: { en: clue[0], et: clue[1] },
        response: { en: response[0], et: response[1] },
        acceptedVariants: { en: variants[0], et: variants[1] },
        explanation: { en: explanation[0], et: explanation[1] },
        source: source(reference),
      };
    }),
  };
}

