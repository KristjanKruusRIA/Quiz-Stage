export function applyAccessibleEasyQuestions(
  rows: readonly Record<string, string>[],
  questions: readonly AccessibleEasyQuestion[],
  openTdbInspirations: readonly OpenTdbInspiration[] = [],
): { rows: Array<Record<string, string>>; evidence: ContentEvidence[]; replacedClueIds: string[] } {
  if (questions.length !== 40) throw new Error(`An accessible-easy batch requires 40 questions; found ${questions.length}`);
  const batchIds = new Set(questions.map((question) => question.batchId));
  if (batchIds.size !== 1) throw new Error('Accessible-easy replacement questions must belong to one batch');

  const categoryRows = new Map<string, Array<Record<string, string>>>();
  for (const row of rows) {
    if (row.content_kind !== 'board' || row.difficulty !== 'easy') continue;
    const set = categoryRows.get(row.category_set_id) ?? [];
    set.push(row);
    categoryRows.set(row.category_set_id, set);
  }
  const slots = [...categoryRows.values()].slice(0, 8);
  if (slots.length !== 8 || slots.some((slot) => slot.length !== 5)) {
    throw new Error('Accessible-easy replacement requires eight complete easy category sets');
  }

  const replacements = new Map<string, Record<string, string>>();
  const evidence: ContentEvidence[] = [];
  const replacedClueIds: string[] = [];
  for (const [setIndex, slot] of slots.entries()) {
    const orderedSlot = [...slot].sort((left, right) => Number(left.tier) - Number(right.tier));
    const questionSet = questions.slice(setIndex * 5, setIndex * 5 + 5);
    for (const [tierIndex, row] of orderedSlot.entries()) {
      const question = questionSet[tierIndex];
      const clueId = `${row.pack_id}-accessible-easy-${String(setIndex * 5 + tierIndex + 1).padStart(3, '0')}`;
      replacedClueIds.push(row.clue_id);
      replacements.set(row.clue_id, {
        ...row,
        clue_id: clueId,
        clue_en: question.clue.en,
        clue_et: question.clue.et,
        response_en: question.response.en,
        response_et: question.response.et,
        accepted_variants_en: '',
        accepted_variants_et: '',
        explanation_en: question.explanation.en,
        explanation_et: question.explanation.et,
        source_title: question.source.title,
        source_url: question.source.url,
        source_license: question.source.license,
        source_retrieved_at: '2026-08-27',
        translation_status: 'reviewed',
        enabled: 'true',
      });
      const inspiration = openTdbInspirations[evidence.length];
      evidence.push({
        version: 1,
        clueId,
        batchId: question.batchId,
        factKey: `accessible-easy:${question.key}`,
        subjectKey: question.subjectKey,
        assertion: `${question.response.en} — ${question.explanation.en}`,
        origin: inspiration === undefined ? 'compatibleOpen' : 'openTdbInspired',
        authoring: {
          author: 'Codex Accessible Trivia Author',
          authoredAt: '2026-08-27T19:00:00.000Z',
        },
        supportingSource: {
          sourceId: question.subjectKey,
          title: question.source.title,
          url: question.source.url,
          license: question.source.license,
          retrievedAt: '2026-08-27',
        },
        inspiration: inspiration ?? null,
        factualReview: {
          reviewer: 'Codex Accessible Trivia Factual Reviewer',
          reviewedAt: '2026-08-27T20:00:00.000Z',
          decision: 'approved',
        },
        editorialReview: {
          reviewer: 'Codex Accessible Trivia Editorial Reviewer',
          reviewedAt: '2026-08-27T20:30:00.000Z',
          decision: 'approved',
        },
        translationReview: {
          reviewer: 'Codex Estonian Semantic Reviewer',
          reviewedAt: '2026-08-27T21:00:00.000Z',
          decision: 'approved',
        },
        adultPolicyReview: null,
      });
    }
  }

  return {
    rows: rows.map((row) => replacements.get(row.clue_id) ?? row),
    evidence,
    replacedClueIds,
  };
}
import type { ContentEvidence } from './evidence';
