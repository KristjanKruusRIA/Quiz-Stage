export interface AccessibleEasyQuestion {
  key: string;
  batchId: string;
  difficulty: 'easy';
  subjectKey: string;
  clue: { en: string; et: string };
  response: { en: string; et: string };
  explanation: { en: string; et: string };
  source: { title: string; url: string; license: 'CC-BY-SA-4.0' };
}

export interface OpenTdbInspiration {
  system: 'OpenTDB';
  candidateId: string;
  license: 'CC-BY-SA-4.0';
}

type RelationEntry = readonly [
  slug: string,
  sourceTitle: string,
  promptEn: string,
  promptEt: string,
  answerEn: string,
  answerEt: string,
];

function relationGroup(
  batchId: string,
  group: string,
  entries: readonly RelationEntry[],
  clue: (prompt: string) => string,
  clueEt: (prompt: string) => string,
  explanation: (prompt: string, answer: string) => string,
  explanationEt: (prompt: string, answer: string) => string,
): AccessibleEasyQuestion[] {
  return entries.map(([slug, sourceTitle, promptEn, promptEt, answerEn, answerEt], index) => ({
    key: `${batchId}-${group}-${String(index + 1).padStart(2, '0')}`,
    batchId,
    difficulty: 'easy',
    subjectKey: `accessible-easy:${batchId}:${slug}`,
    clue: { en: clue(promptEn), et: clueEt(promptEt) },
    response: { en: answerEn, et: answerEt },
    explanation: {
      en: explanation(promptEn, answerEn),
      et: explanationEt(promptEt, answerEt),
    },
    source: {
      title: `${sourceTitle} — Wikipedia`,
      url: `https://en.wikipedia.org/wiki/${slug}`,
      license: 'CC-BY-SA-4.0',
    },
  }));
}

