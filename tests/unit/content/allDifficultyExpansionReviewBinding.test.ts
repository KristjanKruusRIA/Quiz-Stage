import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { expect, it } from 'vitest';
import { EASY_EXPANSION_BATCH_IDS, loadAcceptedEasyExpansionReviews } from '../../../scripts/content/easyExpansion/reviewBinding';
import { acceptedBatchPaths } from '../../../scripts/content/productionBatches';
import { assertAllDifficultyExpansionReviewBindings, loadAcceptedAllDifficultyExpansionReview } from '../../../scripts/content/allDifficultyExpansionReviewBinding';
import { reviewedIdsFromReport } from '../../../scripts/content/validate';
import { readPreRepairContent } from './preRepairContent';

it('retains historical approvals for appended expansion records but rejects changes to reviewed bytes', () => {
  const root = mkdtempSync(join(tmpdir(), 'quiz-stage-expansion-binding-'));
  try {
    for (const batchId of EASY_EXPANSION_BATCH_IDS) {
      const { authored, generated, evidence } = acceptedBatchPaths(batchId);
      for (const relativePath of [authored, generated, evidence, `docs/superpowers/sdd/2026-09-05-accessible-easy-expansion/reviews/${batchId}.json`]) {
        const destination = join(root, relativePath);
        mkdirSync(dirname(destination), { recursive: true });
        if (relativePath.startsWith('content/')) writeFileSync(destination, readPreRepairContent(relativePath));
        else copyFileSync(relativePath, destination);
      }
    }
    const { authored, generated, evidence } = acceptedBatchPaths('01-history');
    for (const relativePath of [authored, generated]) {
      const file = join(root, relativePath);
      writeFileSync(file, `${readFileSync(file, 'utf8')}built-in-history-all-level-expansion-0251,${Array(24).fill('new record').join(',')}\r\n`);
    }
    const evidenceFile = join(root, evidence);
    writeFileSync(evidenceFile, `${readFileSync(evidenceFile, 'utf8')}${JSON.stringify({ clueId: 'built-in-history-all-level-expansion-0251' })}\n`);
    expect(loadAcceptedEasyExpansionReviews(root).size).toBe(12);
    const generatedFile = join(root, generated);
    writeFileSync(generatedFile, readFileSync(generatedFile, 'utf8').replace('Pudding Lane', 'Changed Lane'));
    expect(() => loadAcceptedEasyExpansionReviews(root)).toThrow(/does not match accepted generated bytes/u);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

it('binds new translation exceptions to an independent review and the exact accepted content', () => {
  const root = mkdtempSync(join(tmpdir(), 'quiz-stage-new-expansion-binding-'));
  try {
    const batchId = '01-history';
    const paths = acceptedBatchPaths(batchId);
    const manifest = `docs/superpowers/sdd/2026-10-09-all-difficulty-expansion/reviews/${batchId}.json`;
    for (const relativePath of [paths.authored, paths.generated, paths.evidence, manifest]) {
      const destination = join(root, relativePath);
      mkdirSync(dirname(destination), { recursive: true });
      if (relativePath.startsWith('content/')) writeFileSync(destination, readPreRepairContent(relativePath));
      else copyFileSync(relativePath, destination);
    }
    const { review, binding } = loadAcceptedAllDifficultyExpansionReview(batchId, root);
    const exceptions = review.translationExceptions.map(({ id, reason }) => ({ id, reviewerReason: reason, reviewBinding: binding }));
    expect(() => assertAllDifficultyExpansionReviewBindings(exceptions, root)).not.toThrow();
    const reportPath = join(root, 'release.json');
    const writeReport = (values: Array<{ id: string; reviewerReason: string; reviewBinding?: unknown }>) => writeFileSync(reportPath, JSON.stringify({
      translation: { exceptions: values.map((exception) => ({ ...exception, status: 'reviewed' })) },
    }));
    writeReport(exceptions);
    const reviewedIds = reviewedIdsFromReport(reportPath, { repositoryRoot: root });
    for (const code of ['UNCHANGED_TRANSLATION', 'SUSPICIOUS_PROPER_NOUN_CHANGE']) {
      const decision = exceptions.find(({ id }) => id.startsWith(`${code}:`))!;
      expect(reviewedIds).toContain(decision.id);
      expect(reviewedIds).toContain(`translation:${code}:${decision.id.split(':')[1]}`);
    }
    expect(new Set(reviewedIds).size).toBe(reviewedIds.length);
    writeReport([{ ...exceptions[0], reviewerReason: '' }]);
    expect(reviewedIdsFromReport(reportPath, { repositoryRoot: root })).toEqual([]);
    writeReport([{ ...exceptions[0], reviewBinding: undefined }]);
    expect(() => reviewedIdsFromReport(reportPath, { repositoryRoot: root })).toThrow(/binding/u);
    writeReport([{ ...exceptions[0], id: 'UNCHANGED_TRANSLATION:built-in-history-all-level-expansion-0001:clue_en' }]);
    expect(() => reviewedIdsFromReport(reportPath, { repositoryRoot: root })).toThrow(/reviewed exception/u);
    writeReport(exceptions);
    expect(() => assertAllDifficultyExpansionReviewBindings([{ ...exceptions[0], reviewBinding: undefined }], root)).toThrow(/binding/u);
    expect(() => assertAllDifficultyExpansionReviewBindings([{ ...exceptions[0], id: 'UNCHANGED_TRANSLATION:built-in-history-all-level-expansion-0001:clue_en' }], root)).toThrow(/reviewed exception/u);
    const generated = join(root, paths.generated);
    const original = readFileSync(generated, 'utf8');
    writeFileSync(generated, original.replace('Pudding Lane', 'Changed Lane'));
    expect(() => assertAllDifficultyExpansionReviewBindings(exceptions, root)).toThrow(/accepted generated/u);
    writeFileSync(generated, original.replace('La Comelle', 'Changed Village'));
    expect(() => assertAllDifficultyExpansionReviewBindings(exceptions, root)).toThrow(/accepted generated/u);
    expect(() => reviewedIdsFromReport(reportPath, { repositoryRoot: root })).toThrow(/accepted generated/u);
    writeFileSync(generated, original);
    const reviewPath = join(root, manifest);
    const changed = JSON.parse(readFileSync(reviewPath, 'utf8'));
    changed.translationReview.notes = 'Changed review';
    writeFileSync(reviewPath, `${JSON.stringify(changed)}\n`);
    expect(() => assertAllDifficultyExpansionReviewBindings(exceptions, root)).toThrow(/binding/u);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
